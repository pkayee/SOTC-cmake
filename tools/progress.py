#!/usr/bin/env python3
"""Per-module decomp progress bars from queue/functions.jsonl.
   progress            -> print bars (one line per module + total)
   progress --json     -> machine-readable snapshot (written by the librarian to progress/)
"""
import json, os, re, sys, shutil, subprocess
from pathlib import Path

DECOMP = Path(os.environ.get("SOTC_ROOT", Path(__file__).resolve().parents[1]))
q = Path(os.environ.get("SOTC_QUEUE", DECOMP / "build" / "functions.jsonl"))   # generated by tools/build_queue.py, not committed
UPSTREAM = os.environ.get("SWARM_BASELINE_REF", "59b47f6")   # upstream main when the swarm started
CDEF = re.compile(r"^\+(?!extern\b|typedef\b|INCLUDE_ASM|\+)[A-Za-z_][\w \*]* \**([A-Za-z_]\w*)\s*\([^;]*$")

def swarm_added():
    """function names whose C definition was added since the upstream baseline commit"""
    try:
        diff = subprocess.run(["git", "-C", str(DECOMP), "diff", "-U0", UPSTREAM, "HEAD", "--", "src"],
                              capture_output=True, text=True, timeout=20).stdout
    except Exception: return set()
    return {m.group(1) for m in (CDEF.match(l) for l in diff.splitlines()) if m}
added = swarm_added()

KEYS = ("total", "matched", "base_matched", "swarm_matched", "in_progress", "bytes", "matched_bytes", "swarm_bytes")
mods = {}
for line in q.read_text().splitlines() if q.exists() else []:
    if not line.strip(): continue
    r = json.loads(line)
    m = mods.setdefault(r["module"], {k: 0 for k in KEYS})
    m["total"] += 1; m["bytes"] += r["size"]
    if r["status"] == "matched":
        m["matched"] += 1; m["matched_bytes"] += r["size"]
        if r["name"] in added: m["swarm_matched"] += 1; m["swarm_bytes"] += r["size"]
        else: m["base_matched"] += 1
    elif r["status"] == "in_progress": m["in_progress"] += 1
tot = {k: sum(v[k] for v in mods.values()) for k in KEYS}

if "--json" in sys.argv:
    print(json.dumps({"modules": mods, "total": tot}, indent=1)); sys.exit()

width = shutil.get_terminal_size((100, 20)).columns
label_w = max(len(k) for k in list(mods) + ["TOTAL"]) + 1
bar_w = max(10, width - label_w - 34)
def bar(v):
    n = v["total"] or 1
    pct = v["matched"] / n
    base = int(v["base_matched"] / n * bar_w)                      # upstream baseline: green
    swarm = max(int(pct * bar_w) - base, 1 if v["swarm_matched"] else 0)   # our matches: magenta, stacked right of green
    busy = min(bar_w - base - swarm, int(round(v["in_progress"] / n * bar_w)))
    b = ("\u001b[32m" + "█" * base + "\u001b[95m" + "█" * swarm + "\u001b[33m" + "▒" * busy
         + "\u001b[2m" + "░" * (bar_w - base - swarm - busy) + "\u001b[0m")
    bpct = v["matched_bytes"] / v["bytes"] * 100 if v["bytes"] else 0
    return f"{b} {v['matched']:>4}/{v['total']:<4} {pct*100:5.1f}% \u001b[95m+{v['swarm_matched']:<3}\u001b[0m {bpct:5.1f}% bytes"
for k, v in sorted(mods.items()):
    print(f"{k:<{label_w}}{bar(v)}")
print(f"{'TOTAL':<{label_w}}{bar(tot)}")
print(f"\u001b[2m{'':<{label_w}}\u001b[32m█\u001b[0;2m upstream baseline  \u001b[0;95m█\u001b[0;2m swarm matches (since {UPSTREAM})  "
      f"\u001b[0;33m▒\u001b[0;2m in progress\u001b[0m")
